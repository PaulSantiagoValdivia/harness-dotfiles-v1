printf 'E2E_QA_USER=nuevo\n' > "$TMP_ROOT/front/.env.dev.local"
printf 'E2E_QA_PIN=viejo-en-worktree\n' > "$TMP_ROOT/front/.claude/worktrees/triangulate-vacaciones/.env.test.local"
seed_out="$("$LAUNCHER" seed vacaciones front)"
grep -q 'sembrados 1 archivo' <<<"$seed_out" || fail "seed no sembró exactamente el archivo nuevo: $seed_out"
grep -q 'E2E_QA_USER=nuevo' "$TMP_ROOT/front/.claude/worktrees/triangulate-vacaciones/.env.dev.local" || fail 'seed no copió el .env nuevo'
grep -q 'viejo-en-worktree' "$TMP_ROOT/front/.claude/worktrees/triangulate-vacaciones/.env.test.local" || fail 'seed pisó un .env existente del worktree'
[ -z "$(git -C "$TMP_ROOT/front/.claude/worktrees/triangulate-vacaciones" status --porcelain)" ] || fail 'seed ensució el worktree'
if "$LAUNCHER" seed inexistente front >/dev/null 2>&1; then fail 'seed aceptó un worktree inexistente'; fi
echo 'PASS: seed re-siembra ignorados sin pisar ni trackear; worktree inexistente BLOCKED'
