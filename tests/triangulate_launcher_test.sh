grep -q 'origin/dev es obligatoria' "$LAUNCHER" \
  || fail 'launcher does not enforce origin/dev as the only worktree base'
! grep -q 'symbolic-ref.*refs/remotes/origin/HEAD' "$LAUNCHER" \
  || fail 'launcher can still fall back to a non-dev default branch'

mkdir -p "$TMP_ROOT/back" "$TMP_ROOT/front" "$TMP_ROOT/app"
for repo in back front app; do
  git -C "$TMP_ROOT/$repo" init -q
done
cat > "$TMP_ROOT/triangulate.conf" <<EOF
back=$TMP_ROOT/back
front=$TMP_ROOT/front
app=$TMP_ROOT/app
EOF

codex_plan="$(TRIANGULATE_CONFIG="$TMP_ROOT/triangulate.conf" "$LAUNCHER" plan codex vacaciones)"
grep -q '^topology=primary-plus-two-agent-threads$' <<<"$codex_plan" \
  || fail 'Codex plan does not use one primary plus two threads'
grep -q "canonical=$TMP_ROOT/back/.claude/worktrees/triangulate-vacaciones" <<<"$codex_plan" \
  || fail 'Codex canonical worktree is not backend'
grep -Fq -- "--add-dir $(printf %q "$TMP_ROOT/front/.claude/worktrees/triangulate-vacaciones")" <<<"$codex_plan" \
  || fail 'Codex plan does not grant the front worktree'
grep -Fq -- "--add-dir $(printf %q "$TMP_ROOT/app/.claude/worktrees/triangulate-vacaciones")" <<<"$codex_plan" \
  || fail 'Codex plan does not grant the app worktree'
grep -q -- '--dangerously-bypass-approvals-and-sandbox' <<<"$codex_plan" \
  || fail 'Codex triangulation is not configured for unattended full access'
grep -q 'triangulation-orchestrator' <<<"$codex_plan" \
  || fail 'Codex launch prompt does not activate the coordination skill'

claude_plan="$(TRIANGULATE_CONFIG="$TMP_ROOT/triangulate.conf" "$LAUNCHER" plan claude vacaciones)"
grep -q '^topology=three-named-top-level-sessions$' <<<"$claude_plan" \
  || fail 'Claude plan does not expose three named sessions'
for role in back front app; do
  grep -q "session=vacaciones-$role" <<<"$claude_plan" \
    || fail "Claude plan is missing named $role session"
done

if TRIANGULATE_CONFIG="$TMP_ROOT/triangulate.conf" "$LAUNCHER" plan unknown vacaciones >/dev/null 2>&1; then
  fail 'launcher accepted an unsupported agent provider'
fi

