    for client, slug, change in (('codex', 'vacaciones', 'vacaciones'), ('claude', 'claudealias', 'shared-plan')):
        commands = (tmp / (client + '-commands')).read_bytes().decode().split('\0')[:-1]
        check(commands, client, slug, change)
