        assert contract in protocol, contract
    assert not any((tmp / role / '.claude').exists() for role in roles), 'plan mutated worktrees'
    relative = tmp / 'relative.conf'
    relative.write_text('back=back\nfront=front\napp=app\n')
    result = subprocess.run([str(launcher), 'plan', 'claude', 'relative'], cwd=tmp, env={**env, 'TRIANGULATE_CONFIG': str(relative)}, capture_output=True)
    assert result.returncode != 0 and b'BLOCKED' in result.stderr, result.stdout
