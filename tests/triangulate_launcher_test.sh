    capture.write_text('')
    assert len(commands) == (3 if client == 'claude' else 1), commands
    for command in commands:
        subprocess.run(['bash', '-c', command], env=env, check=True)
    rows = [json.loads(line) for line in capture.read_text().splitlines()]
    assert len(rows) == len(commands)
    nonces = set()
    for index, (name, cwd, args) in enumerate(rows):
        role = roles[index] if client == 'claude' else 'back'
        own = str(tmp / role / '.claude/worktrees' / ('triangulate-' + slug))
        authority = str(tmp / 'back' / '.claude/worktrees' / ('triangulate-' + slug) / 'openspec/changes' / change)
        assert name == client
        if client == 'claude':
            assert args[:2] == ['--name', slug + '-' + role] and len(args) == 3, args
            if not plan: assert cwd == own, (cwd, own)
        else:
            assert args[:3] == ['--dangerously-bypass-approvals-and-sandbox', '--cd', own], args
            assert args[3:-1] == sum((['--add-dir', str(tmp / r / '.claude/worktrees' / ('triangulate-' + slug))] for r in roles[1:]), []), args
        packet = args[-1]
        for field in ('change=' + slug, 'role=' + role, 'worktree=' + own, 'write_boundary=' + own, 'authority=' + authority, 'lead=back'):
            assert field in packet.splitlines(), (field, packet)
        for r in roles:
            assert f'{r}={tmp / r / ".claude/worktrees" / ("triangulate-" + slug)}' in packet.splitlines()
        for artifact in ('proposal.md', 'specs/', 'design.md', 'tasks.md'):
            assert authority + '/' + artifact in packet
        nonce = re.search(r'^run_nonce=([0-9a-f]{32})$', packet, re.M)
        assert nonce, packet
        nonces.add(nonce[1])
        for instruction in ('triangulation-orchestrator', 'HELLO', 'ACK', 'request_id', 'native_identity', 'contract_revision_sha256',
                            'two distinct worker ACKs', 'missing', 'duplicate', 'stale', 'late', 'wrong-role', 'wrong-path', 'wrong-authority',
                            'two discovery attempts', 'event-triggered retry', '10 seconds', 'after second discovery', 'one follow-up', '120 seconds from HELLO', 'no polling',
                            'Missing artifacts', 'read-only discovery', 'canonical SDD planning', 'never fabricate hashes',
                            'revision changes', 'fresh ACK', 'BLOCKED', 'inbox refusal', 'no security bypass', 'UNTESTED'):
            assert instruction in packet, (instruction, packet)
        assert 'Triangula automáticamente' in packet
        if role == 'back': assert 'Own backend implementation, canonical planning and consolidation' in packet
        if role != 'back': assert 'Never create another plan' in packet and 'Do not delegate' in packet
        if client == 'claude': assert 'ListAgents' in packet and 'SendMessage' in packet
        else: assert 'exactly two' in packet and 'front and app' in packet and 'forward' in packet and 'Do not delegate' in packet
    assert len(nonces) == 1 and not seen.intersection(nonces), nonces
    seen.update(nonces)
if mode == 'plan':
    for client in ('claude', 'codex', 'claude'):
        output = subprocess.check_output([str(launcher), 'plan', client, 'vacaciones'], env=env, text=True)
        check([line.removeprefix('command=') for line in output.splitlines() if line.startswith('command=')], client, 'vacaciones', 'vacaciones', True)
    aliases = tmp / 'packet-aliases.conf'; aliases.write_text('vacaciones=packet-contract\n')
    for client in ('codex', 'claude'):
        output = subprocess.check_output([str(launcher), 'plan', client, 'vacaciones'], env={**env, 'TRIANGULATE_CHANGES_CONFIG': str(aliases)}, text=True)
        check([line.removeprefix('command=') for line in output.splitlines() if line.startswith('command=')], client, 'vacaciones', 'packet-contract', True)
