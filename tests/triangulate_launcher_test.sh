#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LAUNCHER="$ROOT/files/shared/bin/triangulate"
TMP_ROOT="$(mktemp -d "${TMPDIR:-/tmp}/triangulate launcher test.XXXXXX")"
